export function matchVerifiedTopicForPrompt(prompt: string, explicitTopicId?: string): VerifiedEducationalTopic | null {
  if (explicitTopicId) {
    const exact = VERIFIED_EDUCATIONAL_TOPICS.find((t) => t.id === explicitTopicId);
    if (exact) return exact;
  }

  const normalized = prompt
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');

  let best: VerifiedEducationalTopic | null = null;
  let bestScore = 0;

  for (const topic of VERIFIED_EDUCATIONAL_TOPICS) {
    let score = 0;
    for (const kw of topic.keywords) {
      const nkw = kw.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
      if (normalized.includes(nkw)) {
        score += nkw.includes(' ') ? 3 : 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = topic;
    }
  }

  return bestScore >= 2 ? best : null;
}

/**
 * Parses explicit user-provided scientific facts (one per line or semicolon-separated)
 * so custom topics never fabricate unverified scientific claims.
 */
export function parseUserEducationalFacts(rawFacts: string | string[] | undefined): string[] {
  if (!rawFacts) return [];
  const items = Array.isArray(rawFacts) ? rawFacts : rawFacts.split(/\n|;/g);
  return items
    .map((line) => line.replace(/^\s*(?:[-•*]|\d+[.):-])\s*/, '').trim())
    .filter((line) => line.length >= 6)
    .slice(0, 8);
}

export function inferEducationalDomain(prompt: string): {
  domain: EducationalDomain;
  scenarioId: string;
  infographicKind: InfographicKind;
  leadCharacterId: string;
} {
  const n = prompt.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  if (/(cerebro|coracao|sangue|corpo|celula|nervo|pulmao|osso|musculo|pele|olho)/.test(n)) {
    return {
      domain: 'corpo_humano',
      scenarioId: 'scene_human_body_cutaway',
      infographicKind: 'organ_zoom',
      leadCharacterId: 'char_pixel_lumi',
    };
  }
  if (/(espaco|planeta|estrela|lua|sol|galaxia|universo|orbita|buraco negro|foguete)/.test(n)) {
    return {
      domain: 'espaco',
      scenarioId: 'scene_retro_space',
      infographicKind: 'solar_orbit',
      leadCharacterId: 'char_pixel_prof_bit',
    };
  }
  if (/(chip|computador|internet|robo|codigo|bateria|eletric|tecnolog|cpu|algoritmo)/.test(n)) {
    return {
      domain: 'tecnologia',
      scenarioId: 'scene_pixel_circuit',
      infographicKind: 'circuit_flow',
      leadCharacterId: 'char_pixel_prof_bit',
    };
  }
  if (/(comida|aliment|fruta|sorvete|cafe|acucar|vitamina|digest|nutri|agua)/.test(n)) {
    return {
      domain: 'alimentacao',
      scenarioId: 'scene_retro_ice_cream',
      infographicKind: 'nutrition_energy',
      leadCharacterId: 'char_pixel_lumi',
    };
  }
  if (/(planta|floresta|animal|oceano|abelha|arvore|ecossistema|natureza|biologia)/.test(n)) {
    return {
      domain: 'natureza',
      scenarioId: 'scene_pixel_forest',
      infographicKind: 'molecule_reaction',
      leadCharacterId: 'char_pixel_lumi',
    };
  }
  if (/(historia|antigo|egito|roma|seculo|descoberta|invencao|galileu|medieval)/.test(n)) {
    return {
      domain: 'historia',
      scenarioId: 'scene_pixel_history',
      infographicKind: 'process_diagram',
      leadCharacterId: 'char_pixel_prof_bit',
    };
  }
  if (/(atomo|molecula|quimica|fisica|luz|som|magnet|energia|ciencia)/.test(n)) {
    return {
      domain: 'ciencia',
      scenarioId: 'scene_pixel_lab',
      infographicKind: 'molecule_reaction',
      leadCharacterId: 'char_pixel_prof_bit',
    };
  }
  return {
    domain: 'curiosidades',
    scenarioId: 'scene_pixel_neon_city',
    infographicKind: 'process_diagram',
    leadCharacterId: 'char_pixel_lumi',
  };
}
