export function resolvePixelGridForAspectRatio(aspectRatio: AspectRatio): PixelGridConfig {
  if (aspectRatio === '16:9') {
    return {
      logicalWidth: 320,
      logicalHeight: 180,
      ditherStrength: 0.72,
      scalingMode: 'nearest',
      paletteName: 'arcade_90s_neon',
      outlinePx: 1,
    };
  }
  if (aspectRatio === '1:1') {
    return {
      logicalWidth: 240,
      logicalHeight: 240,
      ditherStrength: 0.72,
      scalingMode: 'nearest',
      paletteName: 'arcade_90s_neon',
      outlinePx: 1,
    };
  }
  // 9:16 default: 180x320 exact 6x integer scale to 1080x1920!
  return {
    logicalWidth: 180,
    logicalHeight: 320,
    ditherStrength: 0.72,
    scalingMode: 'nearest',
    paletteName: 'arcade_90s_neon',
    outlinePx: 1,
  };
}

